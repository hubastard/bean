def _emit_fallback_typedefs(
    referenced: set[str],
    declared: set[str],
    class_names: set[str],
    skip_names: set[str] | None = None,
    framework_name: str = "",
) -> list[str]:
    skip = skip_names or set()
    blocked = FRAMEWORK_SKIP_FALLBACK_TYPES.get(framework_name, frozenset())
    blocked_prefixes = FRAMEWORK_SKIP_FALLBACK_PREFIXES.get(framework_name, ())
    lines: list[str] = []
    known_structs = set(KNOWN_STRUCT_TYPES.keys()) | set(KNOWN_STRUCT_TYPES.values())
    for name in sorted(referenced):
        if name in declared or name in class_names or name in skip or name in blocked or name in UNSUPPORTED_TYPE_NAMES or name in known_structs:
            continue
        if any(name.startswith(prefix) for prefix in blocked_prefixes):
            continue
        if not name.isidentifier() or not name[0].isupper():
            continue
        if not any(name.endswith(suffix) for suffix in FALLBACK_ENUM_SUFFIXES):
            continue
        lines.extend(_emit_guarded_typedef("NSInteger", name))
    return lines


def _looks_like_enum_typedef(name: str) -> bool:
    return any(name.endswith(suffix) for suffix in FALLBACK_ENUM_SUFFIXES)


def _extra_class_typedefs(
    referenced: set[str],
    class_names: set[str],
    emitted_enum_names: set[str],
    emitted_struct_names: set[str],
    skip_names: set[str] | None,
) -> list[str]:
    skip = skip_names or set()
    out: list[str] = []
    for name in sorted(referenced):
        if name in class_names or name in emitted_enum_names or name in emitted_struct_names or name in skip:
            continue
        if _looks_like_enum_typedef(name):
            continue
        if name.endswith("Struct"):
            continue
        if name in EXTRA_TYPEDEF_BLOCKLIST:
            continue
        if name in KNOWN_STRUCT_TYPES or name in set(KNOWN_STRUCT_TYPES.values()):
            continue
        if not any(name.startswith(prefix) for prefix in EXTRA_TYPEDEF_PREFIXES):
            continue
        if not name.isidentifier():
            continue
        out.extend(_emit_guarded_typedef("bean_id", name))
    return out


