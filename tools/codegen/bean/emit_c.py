def _emit_header_preamble(spec: FrameworkSpec) -> str:
    includes = ['#include "bean/runtime.h"', '#include "bean/types.h"']
    if spec.name == "foundation":
        includes.append("#include <ApplicationServices/ApplicationServices.h>")
    for dep in spec.depends_on:
        includes.append(f'#include "bean/{dep}.h"')
    for native in FRAMEWORK_NATIVE_INCLUDES.get(spec.name, ()):
        includes.append(f"#include {native}")
    if spec.link_symbol:
        includes.append("")
        includes.append(f"/* Force-link {spec.name} framework */")
        includes.append(f"extern void* {spec.link_symbol};")
    return "\n".join(
        [
            f"/* Generated by bean-gen. Do not edit. Framework: {spec.name} */",
            f"#ifndef {spec.guard}",
            f"#define {spec.guard}",
            "",
            *includes,
            "",
            "#ifdef __cplusplus",
            'extern "C" {',
            "#endif",
            "",
        ]
    )


def _emit_header_epilogue() -> str:
    return "\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n"


def _param_decl(name: str, ctype: CType) -> str:
    return f"{ctype.spelling} {_param_name(name, ctype)}"


def _param_name(name: str, ctype: CType) -> str:
    base_type = ctype.spelling.rstrip("*").strip()
    if name == base_type:
        return f"{name}_"
    return name


@dataclass
class EmittedWrapper:
    return_type: str
    fn_name: str
    params_sig: str
    body: str
    doc: str | None = None


MIN_ALIGN_GAP = 4


def _typedef_guard(name: str) -> str:
    return f"BEAN_TYPEDEF_{name}"


def _emit_guarded_typedef(type_spelling: str, name: str) -> list[str]:
    guard = _typedef_guard(name)
    return [
        f"#ifndef {guard}",
        f"#define {guard}",
        f"typedef {type_spelling} {name};",
        "#endif",
    ]


def _pad_to_column(text: str, target_column: int) -> str:
    gap = target_column - len(text)
    if gap > 0:
        return text + (" " * gap)
    return text


def _compute_wrapper_columns(wrappers: list[EmittedWrapper]) -> tuple[int, int]:
    prefix_widths = [len("typedef bean_id")]
    prefix_widths.extend(len(f"static inline {wrapper.return_type}") for wrapper in wrappers)
    name_column = max(prefix_widths) + MIN_ALIGN_GAP

    max_sig_width = 0
    for wrapper in wrappers:
        head = _pad_to_column(f"static inline {wrapper.return_type}", name_column)
        sig = f"{wrapper.fn_name}({wrapper.params_sig})"
        max_sig_width = max(max_sig_width, len(head + sig))

    body_column = max_sig_width + MIN_ALIGN_GAP
    return name_column, body_column


def _format_wrapper_line(
    wrapper: EmittedWrapper,
    name_column: int,
    body_column: int,
) -> str:
    head = _pad_to_column(f"static inline {wrapper.return_type}", name_column)
    sig = f"{wrapper.fn_name}({wrapper.params_sig})"
    return _pad_to_column(head + sig, body_column) + f"{{ {wrapper.body} }}"


def _format_wrappers(
    wrappers: list[EmittedWrapper],
    name_column: int | None = None,
    body_column: int | None = None,
) -> list[str]:
    if not wrappers:
        return []
    if name_column is None or body_column is None:
        name_column, body_column = _compute_wrapper_columns(wrappers)
    lines: list[str] = []
    for wrapper in wrappers:
        if wrapper.doc:
            lines.append(wrapper.doc)
        lines.append(_format_wrapper_line(wrapper, name_column, body_column))
    return lines


def _wrapper_class_deps(wrapper: EmittedWrapper, class_names: set[str]) -> set[str]:
    deps: set[str] = set()
    for token in _extract_type_tokens(wrapper.return_type):
        if token in class_names:
            deps.add(token)
    for token in _extract_type_tokens(wrapper.params_sig):
        if token in class_names:
            deps.add(token)
    return deps


def _class_deps_map(
    by_class: dict[str, list[EmittedWrapper]],
    class_names: set[str],
) -> dict[str, set[str]]:
    deps_map: dict[str, set[str]] = {}
    for class_name, wrappers in by_class.items():
        deps: set[str] = set()
        for wrapper in wrappers:
            deps |= _wrapper_class_deps(wrapper, class_names)
        deps.discard(class_name)
        deps_map[class_name] = deps & set(by_class.keys())
    return deps_map


def _early_forward_classes(
    ordered: list[str],
    deps_map: dict[str, set[str]],
) -> set[str]:
    idx = {name: i for i, name in enumerate(ordered)}
    early: set[str] = set()
    for class_name in ordered:
        for dep in deps_map.get(class_name, set()):
            if idx[dep] > idx[class_name]:
                early.add(dep)
    return early


def _sort_class_blocks(
    by_class: dict[str, list[EmittedWrapper]],
    class_names: set[str],
) -> list[str]:
    classes = list(by_class.keys())
    deps_map = _class_deps_map(by_class, class_names)

    ordered: list[str] = []
    remaining = set(classes)
    while remaining:
        ready = sorted(c for c in remaining if deps_map[c].issubset(set(ordered)))
        if not ready:
            ordered.extend(sorted(remaining))
            break
        for class_name in ready:
            ordered.append(class_name)
            remaining.remove(class_name)
    return ordered


def _emit_class_block(
    class_name: str,
    wrappers: list[EmittedWrapper],
    with_docs: bool,
    docs: DocsIndex | None,
    *,
    skip_typedef: bool = False,
) -> list[str]:
    lines: list[str] = []
    if with_docs and docs:
        class_doc = docs.class_doc(class_name)
        if class_doc:
            lines.append(format_doc_comment(class_doc, None))
    lines.append(f"/* ===== {class_name} ===== */")
    name_column, body_column = _compute_wrapper_columns(wrappers)
    if not skip_typedef:
        lines.extend(_emit_guarded_typedef("bean_id", class_name))
    lines.extend(_format_wrappers(wrappers, name_column, body_column))
    lines.append("")
    return lines


def _emit_variadic_format_method(
    method: ParsedMethod,
    framework: str,
    docs: DocsIndex | None = None,
    with_docs: bool = False,
) -> EmittedWrapper:
    fn_name = c_function_name(method.class_name, method.selector, method.is_class_method)
    format_name = _param_name(method.params[0][0], method.params[0][1])
    format_type = qual_type_to_c(method.params[0][1].spelling).spelling
    doc = None
    if with_docs and docs:
        doc_body = lookup_method_doc(docs, method.class_name, method.selector, method.is_class_method)
        see = objc_method_see(method.class_name, method.selector, method.is_class_method)
        doc = format_doc_comment(doc_body, see)

    if method.selector == "stringWithFormat:" and method.is_class_method:
        params_sig = f"{format_type} {format_name}, ..."
        body = (
            "{ va_list bean_args; va_start(bean_args, "
            f"{format_name}); id bean_tmp = ((id (*)(bean_class, SEL))bean_msgSend)"
            f'(bean_cls("{method.class_name}"), bean_sel("alloc")); id bean_result = '
            f"((id (*)(id, SEL, {format_type}, va_list))bean_msgSend)(bean_tmp, "
            f'bean_sel("initWithFormat:arguments:"), {format_name}, bean_args); '
            f"va_end(bean_args); return bean_result; }}"
        )
        return EmittedWrapper(method.class_name, fn_name, params_sig, body, doc)

    if method.selector == "initWithFormat:":
        params_sig = f"{method.class_name} self, {format_type} {format_name}, ..."
        body = (
            "{ va_list bean_args; va_start(bean_args, "
            f"{format_name}); id bean_result = ((id (*)({method.class_name}, SEL, "
            f"{format_type}, va_list))bean_msgSend)(self, bean_sel(\"initWithFormat:arguments:\"), "
            f"{format_name}, bean_args); va_end(bean_args); return bean_result; }}"
        )
        return EmittedWrapper(method.class_name, fn_name, params_sig, body, doc)

    if method.selector == "initWithFormat:locale:":
        locale_name = _param_name(method.params[1][0], method.params[1][1])
        locale_type = qual_type_to_c(method.params[1][1].spelling).spelling
        params_sig = f"{method.class_name} self, {format_type} {format_name}, {locale_type} {locale_name}, ..."
        body = (
            "{ va_list bean_args; va_start(bean_args, "
            f"{locale_name}); id bean_result = ((id (*)({method.class_name}, SEL, "
            f"{format_type}, {locale_type}, va_list))bean_msgSend)(self, "
            f'bean_sel("initWithFormat:locale:arguments:"), {format_name}, {locale_name}, '
            f"bean_args); va_end(bean_args); return bean_result; }}"
        )
        return EmittedWrapper(method.class_name, fn_name, params_sig, body, doc)

    if method.selector == "appendFormat:":
        params_sig = f"{method.class_name} self, {format_type} {format_name}, ..."
        body = (
            "{ va_list bean_args; va_start(bean_args, "
            f"{format_name}); id bean_piece = ((id (*)(bean_class, SEL))bean_msgSend)"
            '(bean_cls("NSString"), bean_sel("alloc")); bean_piece = '
            f"((id (*)(id, SEL, {format_type}, va_list))bean_msgSend)(bean_piece, "
            f'bean_sel("initWithFormat:arguments:"), {format_name}, bean_args); '
            f"va_end(bean_args); ((void (*)({method.class_name}, SEL, id))bean_msgSend)"
            f'(self, bean_sel("appendString:"), bean_piece); }}'
        )
        return EmittedWrapper("void", fn_name, params_sig, body, doc)

    if method.selector == "localizedStringWithFormat:" and method.is_class_method:
        params_sig = f"{format_type} {format_name}, ..."
        body = (
            "{ va_list bean_args; va_start(bean_args, "
            f"{format_name}); id bean_tmp = ((id (*)(bean_class, SEL))bean_msgSend)"
            f'(bean_cls("{method.class_name}"), bean_sel("alloc")); id bean_locale = '
            '((id (*)(bean_class, SEL))bean_msgSend)(bean_cls("NSLocale"), bean_sel("autoupdatingCurrentLocale")); '
            f"id bean_result = ((id (*)(id, SEL, {format_type}, id, va_list))bean_msgSend)(bean_tmp, "
            f'bean_sel("initWithFormat:locale:arguments:"), {format_name}, bean_locale, bean_args); '
            f"va_end(bean_args); return bean_result; }}"
        )
        return EmittedWrapper(method.class_name, fn_name, params_sig, body, doc)

    raise ValueError(f"unsupported variadic format selector: {method.selector}")


def _method_params(method: ParsedMethod) -> list[tuple[str, CType]]:
    return [
        (name, adjust_parameter_type(method.selector, name, ctype))
        for name, ctype in method.params
    ]


def _emit_method(
    method: ParsedMethod,
    unsupported: list[UnsupportedEntry],
    framework: str,
    docs: DocsIndex | None = None,
    with_docs: bool = False,
) -> EmittedWrapper | None:
    if method.selector in VARIADIC_FORMAT_SELECTORS:
        return _emit_variadic_format_method(method, framework, docs, with_docs)

    adjusted_params = _method_params(method)
    param_types = [p[1] for p in adjusted_params]
    reason = is_unsupported_method(method.selector, param_types, method.return_type)
    if reason:
        unsupported.append(
            UnsupportedEntry(
                class_name=method.class_name,
                selector=method.selector,
                reason=reason,
                framework=framework,
            )
        )
        return None

    fn_name = c_function_name(method.class_name, method.selector, method.is_class_method)
    receiver_type = "bean_class" if method.is_class_method else method.class_name
    if method.is_class_method:
        param_decls = [_param_decl(p[0], p[1]) for p in adjusted_params]
        receiver_expr = f'bean_cls("{method.class_name}")'
    else:
        param_decls = [f"{method.class_name} self"] + [_param_decl(p[0], p[1]) for p in adjusted_params]
        receiver_expr = "self"

    cast = build_msg_send_cast(method.return_type, receiver_type, param_types)

    if method.is_class_method:
        call_args = ", ".join([receiver_expr, f'bean_sel("{method.selector}")'] + [_param_name(p[0], p[1]) for p in adjusted_params])
    else:
        call_args = ", ".join(["self", f'bean_sel("{method.selector}")'] + [_param_name(p[0], p[1]) for p in adjusted_params])

    ret = normalize_return_type_spelling(method.return_type.spelling)
    return_type = ret

    params_sig = ", ".join(param_decls) if param_decls else "void"
    if ret == "void":
        body = f"{cast}({call_args});"
    else:
        body = f"return {cast}({call_args});"
    doc = None
    if with_docs:
        doc_body = lookup_method_doc(docs, method.class_name, method.selector, method.is_class_method)
        see = objc_method_see(method.class_name, method.selector, method.is_class_method)
        doc = format_doc_comment(doc_body, see)
    return EmittedWrapper(return_type, fn_name, params_sig, body, doc)


def _setter_selector(prop_name: str) -> str:
    if not prop_name:
        return "set:"
    return f"set{prop_name[0].upper()}{prop_name[1:] if len(prop_name) > 1 else ''}:"


def _emit_property(
    prop: ParsedProperty,
    unsupported: list[UnsupportedEntry],
    framework: str,
    docs: DocsIndex | None = None,
    with_docs: bool = False,
) -> list[EmittedWrapper]:
    out: list[EmittedWrapper] = []
    if not _type_is_valid(prop.type.spelling):
        return out
    getter_name = c_function_name(prop.class_name, prop.name, False)
    getter_cast = build_msg_send_cast(prop.type, prop.class_name, [])
    getter_doc = None
    if with_docs:
        doc_body = lookup_property_doc(docs, prop.class_name, prop.name)
        see = objc_property_see(prop.class_name, prop.name)
        getter_doc = format_doc_comment(doc_body, see)
    out.append(
        EmittedWrapper(
            normalize_return_type_spelling(prop.type.spelling),
            getter_name,
            f"{prop.class_name} self",
            f"return {getter_cast}(self, bean_sel(\"{prop.name}\"));",
            getter_doc,
        )
    )
    if not prop.readonly:
        setter_sel = _setter_selector(prop.name)
        setter_name = c_function_name(prop.class_name, setter_sel, False)
        setter_cast = build_msg_send_cast(CType("void"), prop.class_name, [prop.type])
        if not _type_is_valid(prop.type.spelling):
            unsupported.append(
                UnsupportedEntry(
                    class_name=prop.class_name,
                    selector=setter_sel,
                    reason="invalid generated type",
                    framework=framework,
                )
            )
        else:
            out.append(
                EmittedWrapper(
                    "void",
                    setter_name,
                    f"{prop.class_name} self, {prop.type.spelling} value",
                    f"{setter_cast}(self, bean_sel(\"{setter_sel}\"), value);",
                )
            )
    return out


def _enum_allowed(name: str, framework_name: str) -> bool:
    if any(name.startswith(prefix) for prefix in ENUM_NAME_BLOCKLIST_PREFIXES):
        return False
    allow = ENUM_PREFIX_ALLOWLIST.get(framework_name)
    if not allow:
        return not (name.startswith("CF") or name.startswith("CG") or name.startswith("kCF"))
    return any(name.startswith(prefix) for prefix in allow)


def _format_enum_constant_value(value: str, underlying: str) -> str:
    """Format enum constant literals to avoid signed-overflow warnings."""
    text = value.strip()
    if not text:
        return text

    signed_max = (1 << 63) - 1

    if text.startswith(("0x", "0X")):
        try:
            numeric = int(text, 16)
        except ValueError:
            return text
        if numeric > signed_max:
            return f"{text}ULL"
        return text

    if text.lstrip("-").isdigit():
        numeric = int(text, 10)
        if numeric > signed_max:
            return f"{text}ULL"
        if numeric < 0:
            return text
        unsigned_underlying = underlying in {
            "NSUInteger",
            "unsigned long",
            "unsigned int",
            "unsigned long long",
            "unsigned",
        }
        if unsigned_underlying and numeric > signed_max:
            return f"{text}ULL"
        return text

    return text


def _emit_enums(enums: list, framework_name: str, skip_names: set[str] | None = None) -> tuple[list[str], set[str]]:
    skip = skip_names or set()
    blocks: list[str] = []
    emitted: set[str] = set()
    for enum in enums:
        if enum.name in skip:
            continue
        if not enum.constants or not _enum_allowed(enum.name, framework_name):
            continue
        filtered_constants = [
            c for c in enum.constants if _enum_allowed(c.name, framework_name)
        ]
        if not filtered_constants:
            continue
        emitted.add(enum.name)
        blocks.extend(_emit_guarded_typedef(enum.underlying, enum.name))
        for constant in filtered_constants:
            if constant.value is not None:
                formatted = _format_enum_constant_value(constant.value, enum.underlying)
                blocks.append(
                    f"static const {enum.name} {constant.name} = ({enum.name}){formatted};"
                )
            else:
                blocks.append(f"static const {enum.name} {constant.name} = ({enum.name})0;")
        blocks.append("")
    return blocks, emitted


