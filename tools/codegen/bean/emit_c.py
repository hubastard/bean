def _collect_referenced_types(methods: list[ParsedMethod], properties: list[ParsedProperty]) -> set[str]:
    referenced: set[str] = set()
    for method in methods:
        for token in _extract_type_tokens(method.return_type.spelling):
            referenced.add(token)
        for _, ctype in method.params:
            for token in _extract_type_tokens(ctype.spelling):
                referenced.add(token)
    for prop in properties:
        for token in _extract_type_tokens(prop.type.spelling):
            referenced.add(token)
    return referenced


def _extract_type_tokens(spelling: str) -> set[str]:
    if not spelling or spelling == "void":
        return set()
    tokens: set[str] = set()
    cleaned = spelling.replace("const ", "").replace("struct ", "").replace("enum ", "")
    cleaned = cleaned.replace("*", " ").replace("(", " ").replace(")", " ")
    for part in cleaned.split():
        if part and part[0].isupper() and part not in PRIMITIVE_TYPES:
            tokens.add(part)
    return tokens


def _collect_used_types(methods: list[ParsedMethod], properties: list[ParsedProperty]) -> set[str]:
    used: set[str] = set()
    for method in methods:
        if method.return_type.spelling not in ("void", "id", "BOOL", "Class", "SEL"):
            used.add(method.return_type.spelling.rstrip("*").strip())
        for _, ctype in method.params:
            used.add(ctype.spelling.rstrip("*").strip())
    for prop in properties:
        used.add(prop.type.spelling.rstrip("*").strip())
    return used


def _normalize_field_type(spelling: str) -> str:
    text = spelling.strip()
    if text.startswith("enum "):
        return text[5:].strip()
    if text.startswith("struct ") and text[7:].strip() in KNOWN_STRUCT_TYPES:
        return KNOWN_STRUCT_TYPES[text[7:].strip()]
    return text


def _emit_structs(structs: list, framework_name: str, used_types: set[str], skip_names: set[str] | None = None) -> tuple[list[str], set[str]]:
    skip = skip_names or set()
    known_structs = set(KNOWN_STRUCT_TYPES.keys()) | set(KNOWN_STRUCT_TYPES.values())
    blocks: list[str] = []
    emitted: set[str] = set()
    for struct in structs:
        if struct.name in skip or struct.name in known_structs:
            continue
        if not _enum_allowed(struct.name, framework_name):
            continue
        if not _struct_is_emittable(struct, used_types):
            continue
        emitted.add(struct.name)
        blocks.append(f"typedef struct {struct.name} {{")
        for field in struct.fields:
            blocks.append(f"    {_format_field_decl(_normalize_field_type(field.type_spelling), field.name)};")
        blocks.append(f"}} {struct.name};")
        blocks.append("")
    return blocks, emitted


def emit_framework_header(
    spec: FrameworkSpec,
    parse_result: ParseResult,
    skip_names: set[str] | None = None,
    skip_functions: set[str] | None = None,
    docs: DocsIndex | None = None,
    with_docs: bool = False,
) -> tuple[str, list[UnsupportedEntry]]:
    unsupported: list[UnsupportedEntry] = []
    methods = dedupe_methods(parse_result.methods)
    properties = dedupe_properties(parse_result.properties)
    method_fn_names: set[str] = set()
    for method in methods:
        if not method.class_name or not method.selector:
            continue
        method_fn_names.add(c_function_name(method.class_name, method.selector, method.is_class_method))
    enums = dedupe_enums(parse_result.enums)
    structs = dedupe_structs(parse_result.structs)
    used_types = _collect_used_types(methods, properties)

    class_names: set[str] = set()
    for item in methods:
        if item.class_name:
            class_names.add(item.class_name)
    for item in properties:
        if item.class_name:
            class_names.add(item.class_name)

    by_class: dict[str, list[EmittedWrapper]] = defaultdict(list)
    seen_functions: set[str] = set()

    skip_funcs = skip_functions or set()

    def add_function(class_name: str, wrapper: EmittedWrapper, fn_name: str) -> None:
        if fn_name in seen_functions or fn_name in skip_funcs:
            return
        seen_functions.add(fn_name)
        by_class[class_name].append(wrapper)

    for method in methods:
        if not method.class_name or not method.selector:
            continue
        emitted = _emit_method(method, unsupported, spec.name, docs, with_docs)
        if emitted:
            fn_name = c_function_name(method.class_name, method.selector, method.is_class_method)
            add_function(method.class_name, emitted, fn_name)

    for prop in properties:
        if not prop.name:
            continue
        getter_fn = c_function_name(prop.class_name, prop.name, False)
        getter_class_fn = c_function_name(prop.class_name, prop.name, True)
        if (
            getter_fn in method_fn_names
            or getter_class_fn in method_fn_names
            or getter_fn in skip_funcs
            or getter_class_fn in skip_funcs
        ):
            continue
        for wrapper in _emit_property(prop, unsupported, spec.name, docs, with_docs):
            add_function(prop.class_name, wrapper, wrapper.fn_name)

    chunks = [_emit_header_preamble(spec)]
    emitted_enum_names: set[str] = set()
    emitted_struct_names: set[str] = set()
    if spec.emit_parsed_types:
        enum_block, emitted_enum_names = _emit_enums(enums, spec.name, skip_names)
        if enum_block:
            chunks.append("/* ===== enums ===== */")
            chunks.extend(enum_block)
        struct_block, emitted_struct_names = _emit_structs(structs, spec.name, used_types, skip_names)
        if struct_block:
            chunks.append("/* ===== structs ===== */")
            chunks.extend(struct_block)
    else:
        chunks.append("/* C API types come from the macOS SDK via bean/types.h and framework dependencies. */")
        chunks.append("")

    referenced_types = _collect_referenced_types(methods, properties)
    block_classes = set(by_class.keys())
    sorted_blocks = _sort_class_blocks(by_class, class_names) if spec.emit_parsed_types else []
    deps_map = _class_deps_map(by_class, class_names)
    early_forward = _early_forward_classes(sorted_blocks, deps_map) if sorted_blocks else set()
    forward_classes = sorted((class_names - block_classes) | early_forward)

    extra_typedefs = _extra_class_typedefs(
        referenced_types, class_names, emitted_enum_names, emitted_struct_names, skip_names
    )
    if extra_typedefs or forward_classes:
        chunks.append("/* ===== forward typedefs ===== */")
        for class_name in forward_classes:
            chunks.extend(_emit_guarded_typedef("bean_id", class_name))
        for line in extra_typedefs:
            chunks.append(line)
        chunks.append("")

    declared_types = (
        class_names
        | emitted_enum_names
        | emitted_struct_names
        | set(KNOWN_STRUCT_TYPES.keys())
        | set(KNOWN_STRUCT_TYPES.values())
        | PRIMITIVE_TYPES
        | {"NSImage", "NSXPCListenerEndpoint", "NSStringEncoding"}
    )
    fallback_typedefs = _emit_fallback_typedefs(
        referenced_types, declared_types, class_names, skip_names, spec.name
    )
    if fallback_typedefs:
        chunks.append("/* ===== fallback typedefs ===== */")
        chunks.extend(fallback_typedefs)
        chunks.append("")

    chunks.extend(_emit_guarded_typedef("bean_id", "NSImage"))
    chunks.extend(_emit_guarded_typedef("bean_id", "NSXPCListenerEndpoint"))
    chunks.extend(_emit_guarded_typedef("NSUInteger", "NSStringEncoding"))
    chunks.append("")

    if spec.emit_parsed_types:
        for class_name in sorted_blocks:
            chunks.extend(
                _emit_class_block(
                    class_name,
                    by_class[class_name],
                    with_docs,
                    docs,
                    skip_typedef=class_name in early_forward,
                )
            )
    chunks.append(_emit_header_epilogue())
    return "\n".join(chunks), unsupported


def emit_unsupported_manifest(entries: list[UnsupportedEntry]) -> str:
    lines = [
        "/* Generated manifest of APIs requiring special handling. */",
        "#ifndef BEAN_UNSUPPORTED_H",
        "#define BEAN_UNSUPPORTED_H",
        "",
        "/*",
    ]
    for entry in sorted(entries, key=lambda e: (e.framework, e.class_name, e.selector)):
        lines.append(f" * [{entry.framework}] {entry.class_name} {entry.selector} — {entry.reason}")
    lines.extend([" */", "", "#endif", ""])
    return "\n".join(lines)
